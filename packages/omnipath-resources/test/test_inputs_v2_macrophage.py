def sheet(*lines, header=HEADER_ROWS):
    """A workbook with the layout of the source: a title, then the header in rows 4 and 5."""
    blank = ('',) * len(COLUMNS)
    title = ('', 'Macrophage Pathway Molecular Interaction') + ('',) * 19
    book = openpyxl.Workbook()
    book.active.title = SHEET
    for line in (blank, title, blank, *header, *lines):
        book.active.append(line)
    content = io.BytesIO()
    book.save(content)
    return SimpleNamespace(result=io.BytesIO(content.getvalue()))


